package br.com.presentedacegonha.dao;

import br.com.presentedacegonha.config.DatabaseConnection;
import br.com.presentedacegonha.model.Usuario;
import br.com.presentedacegonha.security.SenhaHasher;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;

public class UsuarioDAO {

    private static final String CRIAR_TABELA = """
            CREATE TABLE IF NOT EXISTS usuarios (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome VARCHAR(120) NOT NULL,
                email VARCHAR(254) NOT NULL UNIQUE,
                senha_hash VARCHAR(255) NOT NULL,
                criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """;

    public boolean cadastrar(String nome, String email, String senha)
            throws SQLException {
        String senhaHash = SenhaHasher.gerarHash(senha);
        String sql = """
                INSERT INTO usuarios (nome, email, senha_hash)
                VALUES (?, ?, ?)
                ON CONFLICT (email) DO NOTHING
                RETURNING id
                """;

        try (Connection conexao = DatabaseConnection.getConnection()) {
            garantirTabela(conexao);
            try (PreparedStatement comando = conexao.prepareStatement(sql)) {
                comando.setString(1, nome);
                comando.setString(2, email);
                comando.setString(3, senhaHash);

                try (ResultSet resultado = comando.executeQuery()) {
                    return resultado.next();
                }
            }
        }
    }

    public Usuario autenticar(String email, String senha) throws SQLException {
        String sql = """
                SELECT id, nome, email, senha_hash
                FROM usuarios
                WHERE email = ?
                """;

        try (Connection conexao = DatabaseConnection.getConnection()) {
            garantirTabela(conexao);
            try (PreparedStatement comando = conexao.prepareStatement(sql)) {
                comando.setString(1, email);

                try (ResultSet resultado = comando.executeQuery()) {
                    if (!resultado.next()
                            || !SenhaHasher.verificar(
                                    senha, resultado.getString("senha_hash"))) {
                        return null;
                    }

                    Usuario usuario = new Usuario();
                    usuario.setId(resultado.getLong("id"));
                    usuario.setNome(resultado.getString("nome"));
                    usuario.setEmail(resultado.getString("email"));
                    return usuario;
                }
            }
        }
    }

    private void garantirTabela(Connection conexao) throws SQLException {
        try (PreparedStatement comando =
                     conexao.prepareStatement(CRIAR_TABELA)) {
            comando.execute();
        }
    }
}