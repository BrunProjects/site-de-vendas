package br.com.presentedacegonha.dao;

import br.com.presentedacegonha.config.DatabaseConnection;
import br.com.presentedacegonha.model.Carrinho;
import br.com.presentedacegonha.model.Produto;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.Map;
import java.util.TreeMap;

public class PedidoDAO {

    private static final String CRIAR_TABELAS = """
            CREATE TABLE IF NOT EXISTS pedidos (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
                nome_destinatario VARCHAR(120) NOT NULL,
                telefone VARCHAR(30) NOT NULL,
                cep VARCHAR(9) NOT NULL,
                endereco VARCHAR(180) NOT NULL,
                numero VARCHAR(20) NOT NULL,
                complemento VARCHAR(120),
                cidade VARCHAR(100) NOT NULL,
                estado VARCHAR(2) NOT NULL,
                total NUMERIC(12, 2) NOT NULL,
                status VARCHAR(30) NOT NULL DEFAULT 'Recebido',
                criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            CREATE TABLE IF NOT EXISTS itens_pedido (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
                produto_id BIGINT NOT NULL REFERENCES produtos(id),
                nome_produto VARCHAR(150) NOT NULL,
                preco_unitario NUMERIC(12, 2) NOT NULL,
                quantidade INTEGER NOT NULL CHECK (quantidade > 0),
                subtotal NUMERIC(12, 2) NOT NULL
            )
            """;

    public long criarPedido(
            Long usuarioId,
            Carrinho carrinho,
            String destinatario,
            String telefone,
            String cep,
            String endereco,
            String numero,
            String complemento,
            String cidade,
            String estado) throws SQLException {
        if (usuarioId == null || usuarioId <= 0 || carrinho == null
                || carrinho.estaVazio()) {
            throw new IllegalArgumentException("Pedido ou usuário inválido.");
        }

        try (Connection conexao = DatabaseConnection.getConnection()) {
            conexao.setAutoCommit(false);
            try {
                criarTabelas(conexao);
                Map<Long, Integer> itens = new TreeMap<>(carrinho.getItens());
                ArrayList<LinhaPedido> linhas = carregarProdutos(conexao, itens);
                BigDecimal total = linhas.stream()
                        .map(LinhaPedido::getSubtotal)
                        .reduce(BigDecimal.ZERO, BigDecimal::add);
                long pedidoId = inserirPedido(conexao, usuarioId, destinatario,
                        telefone, cep, endereco, numero, complemento,
                        cidade, estado, total);
                gravarItensEReduzirEstoque(conexao, pedidoId, linhas);
                conexao.commit();
                return pedidoId;
            } catch (SQLException e) {
                conexao.rollback();
                throw e;
            } catch (RuntimeException e) {
                conexao.rollback();
                throw e;
            }
        }
    }

    private void criarTabelas(Connection conexao) throws SQLException {
        for (String sql : CRIAR_TABELAS.split(";")) {
            if (!sql.isBlank()) {
                try (PreparedStatement comando = conexao.prepareStatement(sql)) {
                    comando.execute();
                }
            }
        }
    }

    private ArrayList<LinhaPedido> carregarProdutos(
            Connection conexao,
            Map<Long, Integer> itens) throws SQLException {
        String sql = """
                SELECT id, nome, preco, estoque, ativo
                FROM produtos
                WHERE id = ?
                FOR UPDATE
                """;
        ArrayList<LinhaPedido> linhas = new ArrayList<>();

        try (PreparedStatement comando = conexao.prepareStatement(sql)) {
            for (Map.Entry<Long, Integer> item : itens.entrySet()) {
                comando.setLong(1, item.getKey());
                try (ResultSet resultado = comando.executeQuery()) {
                    if (!resultado.next() || !resultado.getBoolean("ativo")) {
                        throw new IllegalArgumentException(
                                "Um produto do carrinho não está disponível.");
                    }
                    int quantidade = item.getValue();
                    int estoque = resultado.getInt("estoque");
                    if (quantidade <= 0 || quantidade > estoque) {
                        throw new IllegalArgumentException(
                                "Estoque insuficiente para "
                                        + resultado.getString("nome") + ".");
                    }
                    linhas.add(new LinhaPedido(
                            resultado.getLong("id"),
                            resultado.getString("nome"),
                            resultado.getBigDecimal("preco"),
                            quantidade));
                }
            }
        }
        return linhas;
    }

    private long inserirPedido(
            Connection conexao,
            Long usuarioId,
            String destinatario,
            String telefone,
            String cep,
            String endereco,
            String numero,
            String complemento,
            String cidade,
            String estado,
            BigDecimal total) throws SQLException {
        String sql = """
                INSERT INTO pedidos
                    (usuario_id, nome_destinatario, telefone, cep,
                     endereco, numero, complemento, cidade, estado, total)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                RETURNING id
                """;
        try (PreparedStatement comando = conexao.prepareStatement(sql)) {
            comando.setLong(1, usuarioId);
            comando.setString(2, destinatario);
            comando.setString(3, telefone);
            comando.setString(4, cep);
            comando.setString(5, endereco);
            comando.setString(6, numero);
            comando.setString(7, complemento);
            comando.setString(8, cidade);
            comando.setString(9, estado);
            comando.setBigDecimal(10, total);
            try (ResultSet resultado = comando.executeQuery()) {
                if (!resultado.next()) {
                    throw new SQLException("O pedido não recebeu um ID.");
                }
                return resultado.getLong("id");
            }
        }
    }

    private void gravarItensEReduzirEstoque(
            Connection conexao,
            long pedidoId,
            ArrayList<LinhaPedido> linhas) throws SQLException {
        String inserirItem = """
                INSERT INTO itens_pedido
                    (pedido_id, produto_id, nome_produto,
                     preco_unitario, quantidade, subtotal)
                VALUES (?, ?, ?, ?, ?, ?)
                """;
        String atualizarEstoque = """
                UPDATE produtos
                SET estoque = estoque - ?
                WHERE id = ? AND ativo = TRUE AND estoque >= ?
                """;

        try (PreparedStatement itemComando =
                     conexao.prepareStatement(inserirItem);
             PreparedStatement estoqueComando =
                     conexao.prepareStatement(atualizarEstoque)) {
            for (LinhaPedido linha : linhas) {
                itemComando.setLong(1, pedidoId);
                itemComando.setLong(2, linha.produtoId);
                itemComando.setString(3, linha.nome);
                itemComando.setBigDecimal(4, linha.precoUnitario);
                itemComando.setInt(5, linha.quantidade);
                itemComando.setBigDecimal(6, linha.getSubtotal());
                itemComando.executeUpdate();

                estoqueComando.setInt(1, linha.quantidade);
                estoqueComando.setLong(2, linha.produtoId);
                estoqueComando.setInt(3, linha.quantidade);
                if (estoqueComando.executeUpdate() != 1) {
                    throw new SQLException(
                            "O estoque mudou durante a finalização do pedido.");
                }
            }
        }
    }

    private static final class LinhaPedido {

        private final long produtoId;
        private final String nome;
        private final BigDecimal precoUnitario;
        private final int quantidade;

        private LinhaPedido(
                long produtoId,
                String nome,
                BigDecimal precoUnitario,
                int quantidade) {
            this.produtoId = produtoId;
            this.nome = nome;
            this.precoUnitario = precoUnitario;
            this.quantidade = quantidade;
        }

        private BigDecimal getSubtotal() {
            return precoUnitario.multiply(BigDecimal.valueOf(quantidade));
        }
    }
}